const HIDDEN_FOLDER_NAMES = new Set([
  "Comments",
  "Favorites",
  "History",
  "Selection Sets",
  "Sensors",
  "Design Binder",
  "Annotations",
  "Surface Bodies",
  "Solid Bodies",
  "Lights and Cameras",
  "Markups",
  "Material <not specified>",
]);

const TABLE_EQN_TYPES = new Set([
  "ConfigTableFolder",
  "TableFolder",
  "EqnFolder",
  "DesignTableFeature",
]);

const GEOMETRY_TYPES = new Set(["RefPlane", "OriginProfileFeature"]);

const hiddenFolder = {
  name: "Hidden",
  type: "Folder",
  path: "Hidden",
  index: -1,
  folder: true,
  children: [],
};

const isSketch = (node) => node.type === "ProfileFeature";
const isTopLevelSketch = (node) => isSketch(node) && !node.path.includes("/");
const isConsumedSketch = (node) => isSketch(node) && node.path.includes("/");
const isTableEqn = (node) => TABLE_EQN_TYPES.has(node.type);
const isGeometry = (node) => GEOMETRY_TYPES.has(node.type);

const buildConsumedSketchSet = (tree) => {
  const set = new Set();

  const walk = (node) => {
    if (isConsumedSketch(node)) {
      const parts = node.path.split("/");
      set.add(parts.at(-1));
    }
    if (Array.isArray(node.children)) {
      node.children.forEach(walk);
    }
  };

  tree.forEach(walk);
  return set;
};

const partitionFeatureTreeAdvanced = (tree) => {
  const hidden = [];
  const visible = [];
  const tableEqn = [];
  const geometry = [];

  for (const node of tree) {
    if (HIDDEN_FOLDER_NAMES.has(node.name)) {
      hidden.push(node);
      continue;
    }

    if (isTableEqn(node)) {
      tableEqn.push(node);
      continue;
    }

    if (isGeometry(node)) {
      geometry.push(node);
      continue;
    }

    visible.push(node);
  }

  return { hidden, visible, tableEqn, geometry };
};

